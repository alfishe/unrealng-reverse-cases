; graphics.asm: Sprite images
;
; The sprites are drawn column by column: a column is the sprite's height in bytes, the columns follow each other, and
; a sprite comes as 4 or 8 copies pre-shifted by 2 or 1 pixel. A sprite descriptor (16 bytes in $7E94-$7F5x: the
; image, the frame and shift strides, the shift mask, the lines and columns) says which.
;
; In block 2 the images of $E000-$E747 and $F048-$F107 are stored complemented; the start-up ($B6FF) inverts them in
; place, so in play a clear bit shows the object's colour (its attribute +$25 is a paper colour) and a set bit keeps
; the cell black. The sprite cache images ($E748-$F047) are built in play from the wave cells; the tape bytes there
; are a leftover of the mastering session.
; --------------------------------------------------------------------------------------------------------------------

; 8 bytes above the player's image (blank in play)
