SCREENS, ZONE = 125, 25
ROWS = 22                                   # the play area: character rows 0-21 (176 pixel lines)
ATTR, CELLTYPES, OPENCELLS = 0x5800, 0x6100, 0x5B00
STAR_FONT, FIELD_FONT = 0xE840, 0xDAB8
KIND_FIELD = 17
# KindTable $8EF4: record n at $8EE8 + 6n (kinds 2-17): the list, the write pointer, the record size, the map
# value after indexing
KIND_RECORDS = 0x8EE8


def cell_attr(d, e):
    """the attribute address PrintChar $ADE1 writes for row d, column e (8-bit registers)"""
    hi = (d & 0xF8) | 0x40
    return ((((hi + 7) & 0xFF) >> 3) & 3 | 0x58) << 8 | ((((d & 7) << 5) + e) & 0xFF)


class Memory(B.Canvas):
    """PrintString's glyphs written into a 64 K memory as PrintChar does (plot mode 0)"""

    def __init__(self, image):
        super().__init__(image)
        self.ram = bytearray(image)
        self.outside = []

    def put(self, d, e, ch, font, c, ctype, mark):
        super().put(d, e, ch, font, c, ctype, mark)
        if e & 0x20:
            return
        if not print_char(self.ram, font, ch, d, e, c, ctype, mark):
            self.outside.append((d, e))


def print_char(ram, font, ch, d, e, c, ctype, mark):
    """PrintChar $ADE1 (no clip test): the glyph, the attribute, the cell type and open-cell maps; False when the
    attribute falls outside the play area"""
    d, e = d & 0xFF, e & 0xFF
    a = (font + 8 * ch) & 0xFFFF
    hi = (d & 0xF8) | 0x40
    lo = (((d & 7) << 5) + e) & 0xFF
    for y in range(8):
        ram[((hi + y) & 0xFF) << 8 | lo] = ram[(a + y) & 0xFFFF]
    at = cell_attr(d, e)
    ram[at] = c
    ram[(at + 0x0900) & 0xFFFF] = ctype
    ram[(at + 0x0300) & 0xFFFF] = mark
    return ATTR <= at < ATTR + 32 * ROWS


def random(state, a=0):
    """Random $AD36: seed = 13 (seed + 7); returns (A XOR the new seed's high byte, the new seed)"""
    s = ((state + 7) * 13) & 0xFFFF
    return a ^ s >> 8, s


def print_char_attr(ram, font, ch, d, e, c):
    """PrintCharAttr $AE26: the glyph and the attribute, no clipping, no maps"""
    a = (font + 8 * ch) & 0xFFFF
    hi = (d & 0xF8) | 0x40
    lo = (((d & 7) << 5) + e) & 0xFF
    for y in range(8):
        ram[((hi + y) & 0xFF) << 8 | lo] = ram[(a + y) & 0xFFFF]
    ram[cell_attr(d, e)] = c


def draw_stars(ram, seed, alt=0):
    """DrawStars $A2D5 over AttrCopy $5E00 (the attributes as SaveAttributes left them). The first Random of a try
    XORs the A that EX AF,AF' brings back (alt: the attribute the last try read, 3 after a star, the caller's A' on
    the first try); the second gets A = 0. Returns (the seed, alt) after."""
    for b in range(ROWS, 0, -1):
        for _ in range(3):
            v, seed = random(seed, alt)
            e, d = v & 0x1F, b - 1
            alt = ram[0x5E00 + 32 * d + e]
            if alt == 0:
                v, seed = random(seed, 0)
                print_char_attr(ram, STAR_FONT, 3, d, e, (v & 7) | 0x42)
                alt = 3
    return seed, alt


def index_object_cells(ram):
    """IndexObjectCells $8E86: the kinds' lists (kind -> [(column, row)]), the map bytes replaced"""
    lists = {}
    for i in range(0x2C0):
        k = ram[CELLTYPES + i]
        if k < 2:
            continue
        lists.setdefault(k, []).append((i & 31, i >> 5))
        rec = KIND_RECORDS + 6 * k
        ram[CELLTYPES + i] = ram[rec + 5]
    return lists


def force_field(ram, lists):
    """ForceFieldDraw $AB97: down from under the first kind 17 cell while the cell type map holds 0; the cells"""
    cells = lists.get(KIND_FIELD)
    if not cells:
        return []
    e, d = cells[0]
    d += 1
    drawn = []
    while True:
        print_char(ram, FIELD_FONT, 0x25, d, e, 1, 1, 0)
        drawn.append((d, e))
        d += 1
        if ram[CELLTYPES + 32 * d + e] != 0:
            return drawn


def build(n, seed=0, image=None, stars=True, alt=0):
    """screen n as BuildScreen draws it; returns (ram, the RAM before the stars, the force field cells, new seed)"""
    image = image or B.image()
    cv = Memory(image)
    ram = cv.ram
    for a in range(ATTR, ATTR + 32 * ROWS):        # ClearPlayArea
        ram[a] = 0
    for y in range(8 * ROWS):
        base = 0x4000 | (y & 0xC0) << 5 | (y & 7) << 8 | (y & 0x38) << 2
        ram[base:base + 32] = bytes(32)
    for a in range(OPENCELLS, OPENCELLS + 0x2C0):  # FillOpenMap, ClearBlockMap
        ram[a] = 0xFF
    for a in range(CELLTYPES, CELLTYPES + 0x2C0):
        ram[a] = 0
    st = {'font': B.word(image, 0xADEF) or 0xD7E0, 'ctype': 1, 'mark': 0, 'marks': []}
    for d, e, el in B.screen_list(n, image):
        st['ctype'], st['mark'] = 1, 0
        B.print_string(cv, B.element_address(el, image), d, e, 0, st)
        cv.ram = ram
    for r, c, k in st['marks']:                      # $EB n: the cell type map only (plot mode 0)
        ram[CELLTYPES + 32 * (r & 0xFF) + (c & 0xFF)] = k
    assert not cv.outside, (n, cv.outside)
    scenery = bytes(ram)
    ram[0x5E00:0x6100] = ram[0x5800:0x5B00]          # SaveAttributes
    if stars:
        seed, alt = draw_stars(ram, seed, alt)
    lists = index_object_cells(ram)
    field = force_field(ram, lists)
    return ram, scenery, field, (seed, alt), lists


def play_area(ram):
    return B.screen(ram).crop((0, 0, 256, 8 * ROWS))


def full_map(stars=True):
    im = Image.new('RGB', (256 * ZONE, 8 * ROWS * (SCREENS // ZONE)))
    seed, alt = B.word(B.image(), 0xAD51), 0
    for n in range(SCREENS):
        ram, _, _, (seed, alt), _ = build(n, seed, stars=stars, alt=alt)
        im.paste(play_area(ram), (256 * (n % ZONE), 8 * ROWS * (n // ZONE)))
    return im


def save_png(im, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    im.save(path, optimize=False, compress_level=9)
    print('wrote', os.path.relpath(path, CASE), f'{im.width}x{im.height}', f'{os.path.getsize(path) // 1024} KB')


def cmd_map(args):
    save_png(full_map(), args.out)


def cmd_check(_args):
    """the stored map against the image's: the pixels (the PNG coder may differ between Pillow versions)"""
    stored = Image.open(MAP_PNG).convert('RGB')
    fresh = full_map()
    if stored.size != fresh.size or stored.tobytes() != fresh.tobytes():
        print('map: src/res/maps/exolon-map.png differs from the image\'s map (tools/fig_map.py map)')
        return 1
    print('map: src/res/maps/exolon-map.png is the image\'s map, pixel for pixel')
    return 0


