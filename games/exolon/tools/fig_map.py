"""The full map of Exolon from the game image alone: the 125 screens as BuildScreen $8494 draws them, five zones of
25 screens, one row a zone (docs/01-game-design.md, src/res/maps/README.md).

    python3 tools/fig_map.py map [--out src/res/maps/exolon-map.png]   the map at 1x (6400 x 880), from the image
    python3 tools/fig_map.py check                                     the stored map regenerated byte for byte
    python3 tools/fig_map.py stats        the layouts: lists stored twice, pixel layouts, zone against zone
    python3 tools/fig_map.py verify --work work/maps/verify [--port-base 29700] [--screens 0-124]
                                    the model against the game's own BuildScreen on an own instance (warp clones)
    python3 tools/fig_map.py figures      docs/img/design/map.png, map-start.png, map-compare.png (doc 01's figures)
    python3 tools/fig_map.py compare      work/maps/compare/pavero.json: ours against Pavero's map, cell by cell
                                          (work/maps/web/Exolon.png: ZXDB's games-maps/e/Exolon.png)

The model (work/mkgame/original.bin only, no recording): ClearPlayArea $B061 (rows 0-21 black); each record of the
screen's list in ScreenTable $C7F4 (row, column, element) prints the element's string (ElementTable $852E) through
PrintString $AF2B in plot mode 0 (PrintChar $ADE1: the glyph's 8 bytes, the attribute, the cell type map $6100 and
the open-cell map $5B00) with the cell type 1, open 0 and attribute 0 set before each element as $84F8-$8501 does;
SaveAttributes $8E11; DrawStars $A2D5 (three random columns a row, a star where the saved attribute is 0, seeded by
RandomSeed $AD51); IndexObjectCells $8E86 (the object cells into the kinds' lists, the map byte replaced); the
force field ForceFieldDraw $AB97 (character $25 of TileGlyphs, attribute 1, down from under its cell while the cell
type map holds 0). Sprites (the player, aliens, balls, missiles) and the HUD rows 22-23 are not drawn.

The stars are new at every build of a screen (Random); the stored map draws them with one chained seed from
RandomSeed's loaded value 0 through the screens in order: one possible sky. `verify` checks the rule against the
game's seed of each build.
"""
