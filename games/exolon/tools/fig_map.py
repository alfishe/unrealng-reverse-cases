PAVERO = os.path.join(CASE, 'work', 'maps', 'web', 'Exolon.png')   # ZXDB's games-maps/e/Exolon.png (Pavero, 2002)
PAVERO_SHIFT = {n: 2 for n in range(15, 28)}                        # its screens 15-27 sit 2 pixel lines lower
BG = (24, 24, 30)


def label(draw, xy, text, size=13, fill=(235, 235, 235), box=None):
    f = B.font(size)
    if box:
        l, t, r, b = draw.textbbox(xy, text, font=f)
        draw.rectangle((l - 3, t - 2, r + 3, b + 2), fill=box)
    draw.text(xy, text, font=f, fill=fill)


def hue(a):
    """a pixel's colour without BRIGHT: Pavero's PNG draws every colour at full level"""
    import numpy as np
    a = np.asarray(a).astype(int)
    return (a[..., 2] > 0) * 1 + (a[..., 0] > 0) * 2 + (a[..., 1] > 0) * 4


def compare_pavero():
    """per screen: the scenery cells that differ, the sky cells Pavero fills with something else than a star"""
    import numpy as np
    rgb = np.pad(np.asarray(Image.open(PAVERO).convert('RGB'))[:880], ((0, 8), (0, 0), (0, 0)))
    theirs = hue(rgb)
    star = B.image()[STAR_FONT + 24:STAR_FONT + 32]
    starbits = np.array([[b >> (7 - x) & 1 for x in range(8)] for b in star]).astype(bool)
    out = []
    for n in range(SCREENS):
        ram, scen, field, _, lists = build(n, stars=False)
        o = hue(play_area(ram))
        y0, x0 = 176 * (n // ZONE) + PAVERO_SHIFT.get(n, 0), 256 * (n % ZONE)
        t = theirs[y0:y0 + 176, x0:x0 + 256]
        near = {(r + dr, c + dc) for cells in lists.values() for c, r in cells
                for dr in range(-3, 4) for dc in range(-3, 4)}
        near |= {(r, c + dc) for r, c in field for dc in (-1, 0, 1)}
        scenery, sky, stars, far = [], [], 0, []
        for d in range(ROWS):
            for e in range(32):
                oc, tc = o[8 * d:8 * d + 8, 8 * e:8 * e + 8], t[8 * d:8 * d + 8, 8 * e:8 * e + 8]
                if scen[ATTR + 32 * d + e] or (d, e) in field or oc.any():
                    if (oc != tc).any():
                        scenery.append((d, e))
                        if (d, e) not in near and not (PAVERO_SHIFT.get(n) and d == ROWS - 1):
                            far.append((d, e))
                elif tc.any():
                    if ((tc > 0) == starbits).all():
                        stars += 1
                    else:
                        sky.append((d, e))
        out.append({'screen': n, 'shift': PAVERO_SHIFT.get(n, 0), 'scenery': scenery, 'sky': sky,
                    'stars': stars, 'far': far})
    return out, rgb


def cmd_compare(_args):
    out, _ = compare_pavero()
    d = os.path.join(CASE, 'work', 'maps', 'compare')
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, 'pavero.json'), 'w') as f:
        json.dump(out, f)
    print('screens with scenery cells differing:', sum(1 for r in out if r['scenery']),
          'cells:', sum(len(r['scenery']) for r in out))
    print('screens with sky cells holding a sprite or an object:', sum(1 for r in out if r['sky']),
          'cells:', sum(len(r['sky']) for r in out))
    print('scenery differences away from every object cell:', {r['screen']: r['far'] for r in out if r['far']})
    print('stars matched:', sum(r['stars'] for r in out))


def fig_overview(im):
    """the map in 15 lines: each zone in three (9, 8, 8 screens), scaled"""
    w, h = round(256 * 0.45), round(176 * 0.45)
    lines = [(z, list(range(25 * z + a, 25 * z + b))) for z in range(5) for a, b in ((0, 9), (9, 17), (17, 25))]
    head, gap, zone_gap = 34, 3, 28
    H = head + 5 * zone_gap + 15 * (h + gap) + 10
    fig = Image.new('RGB', (1050, H), BG)
    dr = ImageDraw.Draw(fig)
    label(dr, (6, 6), 'Exolon: the 125 screens drawn from the image (BuildScreen $8494), one zone in three lines', 15)
    y = head
    for i, (z, screens) in enumerate(lines):
        if i % 3 == 0:
            label(dr, (6, y + 4), f'Zone {z + 1}: screens {25 * z}-{25 * z + 24}' +
                  ('' if z < 4 else ' (the round ends on the right of 124)'), 13, (200, 220, 255))
            y += zone_gap
        for j, n in enumerate(screens):
            x = 6 + j * (w + 1)
            tile = im.crop((256 * (n % 25), 176 * (n // 25), 256 * (n % 25) + 256, 176 * (n // 25) + 176))
            fig.paste(tile.resize((w, h), Image.LANCZOS), (x, y))
            label(dr, (x + 3, y + 2), str(n), 11, box=(0, 0, 0))
        y += h + gap
    return fig


