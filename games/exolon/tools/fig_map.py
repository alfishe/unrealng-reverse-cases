def cmd_stats(_args):
    """doc 01 1.7.1: the screens whose lists are the same bytes, the distinct pixel layouts, and per pair of zones
    the share of the play area's pixel bytes (rows 0-21, no stars) equal screen for screen"""
    image = B.image()
    lists, pix = {}, {}
    for n in range(SCREENS):
        lists[n] = tuple(B.screen_list(n, image))
        ram = build(n, stars=False)[0]
        pix[n] = b''.join(bytes(ram[0x4000 | (y & 0xC0) << 5 | (y & 7) << 8 | (y & 0x38) << 2:][:32])
                          for y in range(8 * ROWS))
    same = {}
    for n in range(SCREENS):
        same.setdefault(lists[n], []).append(n)
    print('lists stored twice (same bytes, two ScreenTable entries):',
          ', '.join('/'.join(map(str, v)) + ' ($%04X/$%04X)' % tuple(B.word(image, B.SCREENS + 2 * x) for x in v)
                    for v in same.values() if len(v) > 1))
    print('distinct pixel layouts:', len(set(pix.values())))
    for z1 in range(5):
        for z2 in range(z1 + 1, 5):
            eq = [sum(a == b for a, b in zip(pix[25 * z1 + i], pix[25 * z2 + i])) / len(pix[0]) for i in range(ZONE)]
            print(f'zone {z1 + 1} vs zone {z2 + 1}: {100 * sum(eq) / ZONE:.1f} % of the pixel bytes equal')


def screens_arg(text):
    out = []
    for part in text.split(','):
        a, _, b = part.partition('-')
        out += list(range(int(a), int(b or a) + 1))
    return out


class Instance:
    def __init__(self, work, port_base, binary, unreal):
        import kitlib as K
        sys.path.insert(0, os.path.join(K.unreal_root(unreal), 'tools', 'verification', 'analysis'))
        import corpus  # noqa: E402
        self.corpus = corpus
        os.makedirs(work, exist_ok=True)
        here = os.getcwd()
        os.chdir(work)
        try:
            self.process = corpus.mcplib.launch(binary, port_base)
        finally:
            os.chdir(here)
        with open(os.path.join(work, 'session.json'), 'w') as f:
            json.dump({'pid': self.process.pid, 'binary': binary, 'port_base': port_base, 'model': '48K'}, f)
        s = corpus.mcplib.Session(f'http://127.0.0.1:{port_base + 200}/mcp', '48K')
        s.fresh_machine('48K', ram_power_on='zero')
        s.call('control_execution', {'action': 'pause'}, ok=False)
        s.call('invoke_api', {'method': 'PUT', 'path': '/api/v1/emulator/{id}/audio/mixer/master',
                              'body': {'muted': True}}, ok=False)
        s.call('control_execution', {'action': 'take_control'}, ok=False)
        self.s = s
        self.m = corpus.Machine(s, port_base)

    def menu(self):
        """the menu as tests/inputs/w-short.txt plays it: 5 (Kempston), then 1 (start) held: the caller runs on to
        the build and releases it"""
        self.m.post('/steps', {'count': 400_000})
        self.s.call('type_input', {'action': 'press', 'key': '5'})
        self.m.post('/steps', {'count': 400_000})
        self.s.call('type_input', {'action': 'release', 'key': '5'})
        self.m.post('/steps', {'count': 400_000})
        self.s.call('type_input', {'action': 'press', 'key': '1'})

    def until(self, pc):
        r = self.m.post('/skip_until', {'pc': pc, 'max_tstates': 70_000_000})
        regs = self.m.get('/registers')
        got = regs['special']['pc']
        if got != pc:
            raise RuntimeError(f'skip_until ${pc:04X}: stopped at ${got:04X} ({r})')

    def stop(self):
        try:
            self.s.call('emulator_manage', {'action': 'quit'}, ok=False)
        except Exception:
            pass
        try:
            self.process.terminate()
            self.process.wait(10)
        except Exception:
            self.process.kill()


def diff_cells(a, b):
    """the play-area cells whose 8 pixel bytes or attribute differ between two 64 K memories"""
    out = []
    for d in range(ROWS):
        for e in range(32):
            hi = (d & 0xF8) | 0x40
            lo = ((d & 7) << 5) + e
            pa = bytes(a[(hi + y) << 8 | lo] for y in range(8))
            pb = bytes(b[(hi + y) << 8 | lo] for y in range(8))
            at = ATTR + 32 * d + e
            if pa != pb or a[at] != b[at]:
                out.append((d, e))
    return out


def cmd_verify(args):
    sys.path.insert(0, os.path.join(CASE, 'tools'))
    work = os.path.abspath(args.work)
    binary = args.binary or os.environ.get('BIN')
    inst = Instance(work, args.port_base, binary, args.unreal)
    results = []
    try:
        for n in screens_arg(args.screens):
            snap = os.path.join(work, f'warp-{n:03d}.z80')
            import subprocess
            subprocess.run([sys.executable, os.path.join(CASE, 'tools', 'warp_snapshot.py'), str(n), snap],
                           check=True, cwd=CASE)
            inst.m.post('/snapshot/load', {'path': snap})
            inst.menu()
            # the game start: $75BB CALL BuildScreen; $8511 the stars next; $8514 the stars drawn; $75BE built
            inst.until(0x8511)
            pre = inst.m.read(0, 0x10000)
            seed = pre[0xAD51] | pre[0xAD52] << 8
            alt = inst.m.get('/registers')['alternate']['af_'] >> 8
            inst.until(0x8514)
            star = inst.m.read(0, 0x10000)
            inst.until(0x75BE)
            done = inst.m.read(0, 0x10000)
            inst.s.call('type_input', {'action': 'release', 'key': '1'})
            ram, scenery, field, _, lists = build(n, seed, alt=alt)
            r = {'screen': n, 'seed': seed, 'alt': alt, 'font_in': pre[0xADEF] | pre[0xADF0] << 8,
                 'scenery': diff_cells(scenery, pre),
                 'cell_types': sum(1 for i in range(0x2C0) if scenery[CELLTYPES + i] != pre[CELLTYPES + i]),
                 'open_cells': sum(1 for i in range(0x2C0) if scenery[OPENCELLS + i] != pre[OPENCELLS + i]),
                 'stars': diff_cells(_stars_only(scenery, seed, alt), star),
                 'built': diff_cells(ram, done), 'field': field}
            # what changed after the build in the game but not in the model: the objects' set-up (balls, aliens)
            results.append(r)
            print(f"screen {n:3d}: scenery {len(r['scenery'])} cells, types {r['cell_types']}, open "
                  f"{r['open_cells']}, stars {len(r['stars'])}, built {len(r['built'])} {r['built'][:6]}",
                  flush=True)
            if r['built']:
                B.zoom(B.screen(done).crop((0, 0, 256, 176)), 2).save(os.path.join(work, f'game-{n:03d}.png'))
                B.zoom(play_area(ram), 2).save(os.path.join(work, f'model-{n:03d}.png'))
            os.remove(snap)
    finally:
        inst.stop()
    with open(os.path.join(work, 'verify.json'), 'w') as f:
        json.dump(results, f, indent=1)
    print('wrote', os.path.join(args.work, 'verify.json'))


def _stars_only(scenery, seed, alt):
    ram = bytearray(scenery)
    ram[0x5E00:0x6100] = ram[0x5800:0x5B00]
    draw_stars(ram, seed, alt)
    return ram


