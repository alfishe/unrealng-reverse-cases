; cells.asm: The cell table: one byte for each character cell of the play area
;
; The cell table mirrors the attribute file: the cell of screen character (row, column) is $6000 + 32 x row + column,
; so its attribute address is the cell address with H XOR $38. Rows 0-5 ($6000-$60BF) lie under the BASIC program and
; are never play cells; the image holds rows 6-23 ($60C0-$62FF). DrawRoom $6B22 rebuilds it for every room (1 where
; the attribute is not 0: a wall), then puts the room's items and teleporter in; the movers mark the cells they stand
; on (bit 1 an enemy, bit 2 an object, bit 3 a patroller) and the shots the cells they pass (bits 4-6).
; --------------------------------------------------------------------------------------------------------------------

; The cell table, rows 6-23 of the screen: 0 empty, 1 a wall, $80+ an item, $FF
; $FF a teleporter, bits 1-6 the movers' marks
;
; Values: 0 empty; 1 a wall (DrawRoom $6D8C, where the room's attribute is not
; 0); an item's code on its 2 x 2 cells (DrawItem $6E0D: $80 GEN 19, $81 an
; energy source, $C1-$C3 weapons 1-3, $82-$B3 the ED pieces); $FF $FF on the
; two top cells of a teleporter (DrawRoom $6DE3). Marks a mover XORs in and
; out: bit 1 an enemy (MoveEnemy $90E7 through XorCells $7D87 with 2), bit 2 an
; object (4), bit 3 a patroller (8); the shots OR bits 4-6 (OrCells $7DAE: $11,
; $21 and $41 for weapons 3, 2 and 1), which the objects test against their
; kind (ObjectKind $7C28).
;
; Readers: CellAddr $7CAA (the droid's cell, the step tests), CellAddrXY $7C94,
; the touch test of MoveDroid ($75C8), MoveEnemy's spawn ($911B). The bytes in
; the image are the last room of the authors' session (no build reads them
; before DrawRoom writes the table: c1 frame 13580 calls DrawRoom first).
