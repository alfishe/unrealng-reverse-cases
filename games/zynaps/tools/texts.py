#!/usr/bin/env python3
"""Every text of the game image, as UTF-8 with its address.

    python3 texts.py IMAGE.bin [OUT.txt]       # IMAGE: the 64 K memory (the static entry image or a dump)

The messages: a table of $FF-terminated strings from $82EE, numbered from 0 (PrintMessage $A423 skips A $FF
bytes from $82ED). Inside a message (PrintString $A401, PrintChar $A321): $1B n prints message n; a byte below
$20 is a control code that takes the next byte: 0 attribute, 1 ink, 2 paper, 3 column, 4 row, 5 column += n,
6 row += n. Bytes from $80 are the game's own glyphs (at $B54F + (c - $80) * 8: the logo, the frame pieces);
the letters are the ROM font. Shown here: {at r,c} {attr $xx} {ink n} {paper n} {col+n} {row+n} {msg n} {Gxx}.
"""
import sys

CODES = {0: 'attr ${:02X}', 1: 'ink {}', 2: 'paper {}', 3: 'col {}', 4: 'row {}', 5: 'col+{}', 6: 'row+{}'}


def render(m, a, end=0xFF):
    out = []
    while m[a] != end:
        c = m[a]
        if c == 0x1B:
            out.append('{msg %d}' % m[a + 1])
            a += 2
        elif c < 0x20:
            p = m[a + 1]
            if c in (5, 6) and p >= 0x80:
                p -= 256
            out.append('{' + CODES.get(c, 'code %d %%s' % c).format(p) + '}')
            a += 2
        elif c < 0x80:
            out.append(chr(c))
            a += 1
        else:
            out.append('{G%02X}' % c)
            a += 1
    return ''.join(out), a + 1


def bcd(bs):
    return int(''.join('%02X' % b for b in bs))


def main():
    m = open(sys.argv[1], 'rb').read()
    lines = ['# Zynaps (Hewson, 1987): the texts of the game image, generated by tools/texts.py',
             '# address  text (control codes in braces, see the script)', '',
             '## The messages (PrintMessage $A423: message n is the n-th $FF-terminated string from $82EE)']
    a, n = 0x82EE, 0
    while a < 0x8516:
        text, nxt = render(m, a)
        lines.append(f'${a:04X}  msg {n:2d}  {text}')
        a, n = nxt, n + 1
    lines += ['', '## The high-score table ("ROLE OF HONOUR", $8261: 5 entries of 14 bytes: a 10-byte print string '
              'with the initials, then the score, 4 BCD bytes)']
    for i in range(5):
        e = 0x8261 + 14 * i
        text, _ = render(m, e)
        lines.append(f'${e:04X}  {text}  score ${e + 10:04X} = {bcd(m[e + 10:e + 14])}')
    lines += ['', '## The key names (the redefine-keys screen: $8198, 40 entries, one per key in the order of the '
              'half-rows $FEFE..$7FFE, bit 0 first; 0-3 name CS SS SP EN, printed as messages 9-12)']
    names = ['CS', 'SS', 'SP', 'EN']
    keys = [names[b] if b < 4 else chr(b) for b in m[0x8198:0x81C0]]
    for row in range(8):
        lines.append(f'${0x8198 + 5 * row:04X}  ' + ' '.join(keys[5 * row:5 * row + 5]))
    lines += ['', '## The points table ($8234: 4 BCD bytes per award, AddScore $A489 reads entry A from $8234 + 4 A '
              'downwards)']
    pts = []
    for i in range(12):
        lsb = 0x8234 + 4 * i
        pts.append(str(bcd([m[lsb - 3], m[lsb - 2], m[lsb - 1], m[lsb]])))
    lines.append('$8231  ' + ', '.join(pts))
    text = '\n'.join(lines) + '\n'
    if len(sys.argv) > 2:
        open(sys.argv[2], 'w', encoding='utf-8').write(text)
    print(text, end='')


if __name__ == '__main__':
    main()
